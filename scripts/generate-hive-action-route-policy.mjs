#!/usr/bin/env node
// Generates src/lib/services/security/hive-action-route-policy.generated.ts.
//
// Why generated rather than imported: the policy is consumed by src/proxy.ts,
// which is Next middleware. Importing the hive-action catalog there would drag
// every action's service graph into the middleware bundle. A plain data module
// keeps middleware light while staying derived from the catalog rather than
// hand-maintained.
//
// Why only UNAMBIGUOUS routes: 15 routes serve several actions at different risk
// levels (/api/apify carries both apify.search-actors at low and apify.fund at
// critical). Which one a request invokes is decided by its BODY, which
// middleware cannot read. Guessing wrong is unsafe in both directions — taking
// the strictest action would refuse ordinary reads, taking the loosest would wave
// through a payment. Those routes are recorded as ambiguous and deliberately left
// for per-route enforcement where the action is actually known.
//
// Run: node scripts/generate-hive-action-route-policy.mjs [--check]
import { register } from "node:module";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

register(new URL("./lib/ts-relative-loader.mjs", import.meta.url));

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const OUT = path.join(ROOT, "src", "lib", "services", "security", "hive-action-route-policy.generated.ts");
const CHECK = process.argv.includes("--check");

const { listHiveActions } = await import("../src/lib/services/hive-actions/index.ts");
const { requiredClaimsForSideEffects } = await import("../src/lib/services/security/action-authorization.ts");

const byRoute = new Map();
for (const action of listHiveActions()) {
  const route = action.contextIndex?.route;
  if (!route) continue;
  if (!byRoute.has(route)) byRoute.set(route, []);
  byRoute.get(route).push(action);
}

const unambiguous = [];
const ambiguous = [];
for (const [route, actions] of [...byRoute.entries()].sort(([a], [b]) => a.localeCompare(b))) {
  if (actions.length === 1) {
    const action = actions[0];
    unambiguous.push({
      route,
      actionId: action.id,
      risk: action.risk,
      sideEffects: [...action.sideEffects].sort(),
      readOnly: Boolean(action.readOnly),
      requiredClaims: requiredClaimsForSideEffects(action.sideEffects).sort(),
      confirmation: action.confirmation
        ? { reason: action.confirmation.reason, when: action.confirmation.when ?? "always" }
        : null,
    });
  } else {
    ambiguous.push({ route, actionIds: actions.map((a) => a.id).sort() });
  }
}

const body = `// GENERATED by scripts/generate-hive-action-route-policy.mjs — do not edit by hand.
// Re-run that script (or \`pnpm guard:hive-action-route-policy\` to verify) after
// changing any hive action's route, risk, side effects, or confirmation.
//
// Consumed by src/proxy.ts. Keep this a PLAIN DATA module with no imports beyond
// types: it is loaded in Next middleware, and pulling in the action catalog would
// drag every action's service graph into that bundle.
import type { HiveActionConfirmation, HiveActionRisk, HiveActionSideEffect } from "@/lib/services/hive-actions/types";

export type HiveActionRoutePolicy = {
  route: string;
  actionId: string;
  risk: HiveActionRisk;
  sideEffects: HiveActionSideEffect[];
  readOnly: boolean;
  requiredClaims: string[];
  confirmation: Exclude<HiveActionConfirmation, false> | null;
};

/** Routes served by exactly one hive action, so the route determines the policy. */
export const HIVE_ACTION_ROUTE_POLICIES: HiveActionRoutePolicy[] = ${JSON.stringify(unambiguous, null, 2)};

/**
 * Routes served by SEVERAL actions at differing risk. The action is chosen by the
 * request body, which middleware cannot read, so these are intentionally not
 * enforced at the proxy — they need enforcement inside the route handler, where
 * the action is known. Listed rather than silently dropped so the gap is visible.
 */
export const AMBIGUOUS_HIVE_ACTION_ROUTES: Array<{ route: string; actionIds: string[] }> = ${JSON.stringify(ambiguous, null, 2)};

const POLICY_BY_ROUTE = new Map(HIVE_ACTION_ROUTE_POLICIES.map((policy) => [policy.route, policy]));

export function hiveActionRoutePolicy(pathname: string): HiveActionRoutePolicy | null {
  return POLICY_BY_ROUTE.get(pathname) ?? null;
}
`;

if (CHECK) {
  let current = "";
  try {
    current = readFileSync(OUT, "utf8");
  } catch {
    console.error(`${path.relative(ROOT, OUT)} is missing. Run: node scripts/generate-hive-action-route-policy.mjs`);
    process.exit(1);
  }
  if (current !== body) {
    console.error(
      `${path.relative(ROOT, OUT)} is stale.\n`
      + "A hive action's route, risk, side effects, or confirmation changed without regenerating it,\n"
      + "which would leave the proxy enforcing the OLD policy.\n"
      + "Run: node scripts/generate-hive-action-route-policy.mjs",
    );
    process.exit(1);
  }
  console.log(
    `Hive action route policy is current (${unambiguous.length} enforceable routes, ${ambiguous.length} ambiguous).`,
  );
} else {
  writeFileSync(OUT, body);
  console.log(
    `Wrote ${path.relative(ROOT, OUT)}: ${unambiguous.length} enforceable routes, ${ambiguous.length} ambiguous.`,
  );
}
