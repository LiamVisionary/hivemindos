#!/usr/bin/env node
// Regenerates the human-readable Markdown views of the workflow banks from their JSON
// source of truth. Run with --check to fail when the committed Markdown is stale.
//
//   node scripts/build-workflow-docs.mjs
//   node scripts/build-workflow-docs.mjs --check
//
// The JSON is authoritative. Never hand-edit a generated .md — the next build overwrites it.

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");

const readJson = (relative) => JSON.parse(readFileSync(path.join(root, relative), "utf8"));

function renderHooks(bank) {
  const { taxonomy, hooks } = bank;
  const out = [];
  out.push("<!-- Generated by scripts/build-workflow-docs.mjs from hooks.json. Do not edit by hand. -->");
  out.push("---");
  out.push("title: Video Hooks");
  out.push("description: Original short-form video hook frameworks, indexed for agent and app use.");
  out.push("machine_source: ./hooks.json");
  out.push(`count: ${bank.count}`);
  out.push(`provenance: ${bank.provenance}`);
  out.push(`verified_on: ${bank.verifiedOn}`);
  out.push("---");
  out.push("");
  out.push("# Video Hooks");
  out.push("");
  out.push(`${bank.count} hook frameworks for short-form video. Each carries a fill-in-the-blank template, the`);
  out.push("psychological category it belongs to, the audience awareness level it suits, and the formats it");
  out.push("fits. Every hook has a stable id (`H001`–`H0" + String(bank.count).padStart(2, "0") + "`) so agents, prompts, and app code refer to the same hook.");
  out.push("");
  out.push("[`hooks.json`](./hooks.json) is the source of truth. Read it rather than parsing this Markdown,");
  out.push("which is generated by `scripts/build-workflow-docs.mjs`.");
  out.push("");
  out.push("## Provenance");
  out.push("");
  out.push(bank.note);
  out.push("");
  out.push("## For agents: picking a hook");
  out.push("");
  out.push("When a video request needs a hook and the user has not named one, sample at random rather than");
  out.push("defaulting to the first entry. Filter first when the brief gives you something to filter on: a");
  out.push('cold audience wants `awareness` of `"Unaware"` or `"Problem"`; retargeting wants `"Product"` or `"Most"`.');
  out.push("");
  out.push("```bash");
  out.push("# one random hook (sort -R, not shuf — macOS has no shuf)");
  out.push('jq -r \'.hooks[] | "\\(.id) \\(.name): \\(.hook)"\' workflows/video/hooks.json | sort -R | head -n 1');
  out.push("");
  out.push("# random, filtered to cold-audience video hooks");
  out.push("jq -r '.hooks[]");
  out.push('       | select(.awareness=="Unaware" or .awareness=="Problem")');
  out.push('       | select(any(.format[]; contains("Video")))');
  out.push('       | "\\(.id) \\(.name): \\(.hook)"\' workflows/video/hooks.json | sort -R | head -n 1');
  out.push("```");
  out.push("");
  out.push("```js");
  out.push('import bank from "./workflows/video/hooks.json" with { type: "json" };');
  out.push("");
  out.push('const pool = bank.hooks.filter((h) => h.tags.includes("tof"));');
  out.push("const pick = pool[Math.floor(Math.random() * pool.length)];");
  out.push("```");
  out.push("");
  out.push("## Fill every slot before shipping");
  out.push("");
  out.push("Slots are written `[LIKE THIS]` on purpose. The Deliverable Acceptance gate");
  out.push("(`src/lib/services/deliverables/acceptance-contracts.ts`) matches `/\\[[A-Z_ ]{3,}\\]/` and");
  out.push("fail-closes on a hit, so an unfilled hook that reaches a page or script is caught rather than");
  out.push("shipped. That protection only holds while slots stay UPPERCASE, contain no hyphens or digits,");
  out.push("and are at least three characters. Keep new slots in that shape.");
  out.push("");
  out.push("## Index");
  out.push("");
  out.push("| Category | Count | Hooks |");
  out.push("| --- | --- | --- |");
  for (const category of taxonomy.categories) {
    const ids = hooks.filter((h) => h.category === category).map((h) => h.id);
    out.push(`| ${category} | ${ids.length} | ${ids.join(", ")} |`);
  }
  out.push("");
  out.push("---");
  out.push("");
  for (const category of taxonomy.categories) {
    out.push(`## ${category}`);
    out.push("");
    for (const h of hooks.filter((x) => x.category === category)) {
      out.push(`### ${h.id} · ${h.name}`);
      out.push("");
      out.push(`> ${h.hook}`);
      out.push("");
      out.push(`- **Awareness:** ${h.awareness}`);
      out.push(`- **Format:** ${h.format.join(", ")}`);
      out.push(`- **Why it works:** ${h.whyItWorks}`);
      out.push(`- **Best for:** ${h.bestFor}`);
      out.push(`- **Example:** ${h.example}`);
      out.push(`- **Tags:** ${h.tags.map((t) => `\`${t}\``).join(", ")}`);
      out.push("");
    }
  }
  return out.join("\n") + "\n";
}

const targets = [{ source: "workflows/video/hooks.json", output: "workflows/video/HOOKS.md", render: renderHooks }];

let stale = 0;
for (const { source, output, render } of targets) {
  const next = render(readJson(source));
  const outputPath = path.join(root, output);
  const current = (() => {
    try {
      return readFileSync(outputPath, "utf8");
    } catch {
      return null;
    }
  })();

  if (check) {
    if (current !== next) {
      stale += 1;
      console.error(`stale: ${output} — run \`node scripts/build-workflow-docs.mjs\``);
    }
    continue;
  }

  if (current === next) {
    console.log(`unchanged: ${output}`);
  } else {
    writeFileSync(outputPath, next);
    console.log(`wrote: ${output}`);
  }
}

if (check && stale > 0) process.exit(1);
if (check) console.log(`up to date: ${targets.length} file(s)`);
