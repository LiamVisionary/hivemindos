import { createHash } from "node:crypto";
import { watch } from "node:fs";
import { readFile } from "node:fs/promises";

// launchd's WatchPaths is unreliable for in-place edits, so the collector
// watches its own source instead: on a real code change it exits cleanly and
// launchd's KeepAlive relaunches it with the new code — no manual kickstart.
//
// IMPORTANT: gate on CONTENT HASH, not raw fs events. fs.watch fires on mtime
// touches, atomic-save renames, and Syncthing/editor writes that don't change
// content; reacting to every event sent this into a restart LOOP (hundreds of
// reloads) that knocked the collector offline and broke in-flight voice calls.
// A startup grace period also breaks any tight relaunch loop.

const RELOAD_GRACE_MS = 5_000;
const RELOAD_DEBOUNCE_MS = 1_000;

// launchd/systemd KeepAlive relaunch on ANY exit, so unix exits clean. On
// Windows neither a clean nor a failed exit gets relaunched — Task Scheduler's
// -RestartCount only covers tasks that failed to LAUNCH (validated on a real
// box: exit 1 after running left the task Ready, never restarted). The hidden
// supervisor generated by install-telemetry-collector.ps1 is the relauncher: it
// restarts the collector immediately on this dedicated reload code.
export function selfReloadExitCode(platform) {
  return platform === "win32" ? 75 : 0;
}

export function selfReloadHasher(selfPath, readSource = readFile) {
  return async () => {
    try {
      return createHash("sha256").update(await readSource(selfPath)).digest("hex");
    } catch {
      return "";
    }
  };
}

// The debounced body of the watcher, split out so it can be driven directly:
// resolves true when it decided to reload (and called exit), false otherwise.
export function createSelfReloadHandler(dependencies = {}) {
  const {
    hashSource,
    baselineHash,
    startedAt,
    platform = process.platform,
    exit = (code) => process.exit(code),
    log = console.log,
    now = Date.now,
    graceMs = RELOAD_GRACE_MS,
    canReload = () => true,
    onDeferred = () => undefined,
  } = dependencies;
  let reloading = false;

  return async () => {
    if (reloading) return false;
    // Ignore events right after launch so a misbehaving write can't loop us.
    if (now() - startedAt < graceMs) return false;
    const nextHash = await hashSource();
    if (!nextHash || nextHash === baselineHash) return false; // content unchanged
    if (!canReload()) {
      log("[collector] source changed — deferring reload until active chat runs finish");
      onDeferred();
      return false;
    }
    reloading = true;
    const reloadExitCode = selfReloadExitCode(platform);
    log(
      `[collector] source changed — exiting ${reloadExitCode} for ${
        platform === "win32" ? "supervisor restart" : "KeepAlive reload"
      }`,
    );
    exit(reloadExitCode);
    return true;
  };
}

// `selfPath` is injected rather than derived from import.meta.url: the file to
// watch is the collector entrypoint, not this module.
export async function startSelfReloadWatcher(dependencies = {}) {
  const {
    selfPath,
    disabled = process.env.AGENT_TELEMETRY_DISABLE_SELF_RELOAD === "1",
    now = Date.now,
    readSource = readFile,
    watchSource = watch,
    debounceMs = RELOAD_DEBOUNCE_MS,
    ...handlerDependencies
  } = dependencies;
  if (disabled || !selfPath) return false;

  const hashSource = selfReloadHasher(selfPath, readSource);
  const baselineHash = await hashSource();
  if (!baselineHash) return false;

  let pending = null;
  const schedule = (delayMs) => {
    if (pending) clearTimeout(pending);
    pending = setTimeout(() => {
      pending = null;
      void handleChange();
    }, delayMs);
  };
  const handleChange = createSelfReloadHandler({
    ...handlerDependencies,
    baselineHash,
    hashSource,
    now,
    startedAt: now(),
    onDeferred: () => schedule(debounceMs),
  });
  try {
    watchSource(selfPath, { persistent: false }, () => {
      schedule(debounceMs);
    });
  } catch {
    // Auto-reload is a convenience; never block startup on it.
    return false;
  }

  return true;
}
